"""Symbolic knowledge layer: the single source of facts that agents may use (through tools) and the verifier checks
against. Facts come from the scan (dependency graph, findings, SBOM), the repository itself, and public read-only
data (OSV advisories, npm/PyPI registries, deps.dev dependency trees, EPSS/KEV). Nothing here is generated by a model.
"""
from __future__ import annotations

import json
import re
import urllib.parse
import urllib.request
from pathlib import Path

from ..detect.osv import CACHE as OSV_CACHE, _http as osv_http, vkey
from ..detect.packages import _downloads, _get as registry_get

CACHE = Path(__file__).resolve().parents[2] / ".cache"
UA = {"User-Agent": "supply-chain-guardian/0.3"}


def published_versions(package: str, eco: str, offline: bool = False) -> list[str] | None:
    """Stable published versions, oldest -> newest (npm / PyPI)."""
    if eco == "npm":
        req = urllib.request.Request(f"https://registry.npmjs.org/{urllib.parse.quote(package, safe='@')}",
                                     headers={"Accept": "application/vnd.npm.install-v1+json", **UA})
    elif eco == "PyPI":
        req = urllib.request.Request(f"https://pypi.org/pypi/{package}/json", headers=UA)
    else:
        return None
    f = CACHE / "versions" / (re.sub(r"[^\w.-]", "_", f"{eco}_{package}") + ".json")
    if f.exists():
        return json.loads(f.read_text(encoding="utf-8"))
    if offline:
        return None
    try:
        with urllib.request.urlopen(req, timeout=20) as r:
            data = json.loads(r.read())
    except Exception:
        return None
    vs = list((data.get("versions") or {}).keys()) if eco == "npm" else list((data.get("releases") or {}).keys())
    vs = sorted((v for v in vs if re.match(r"^\d+(\.\d+)*$", v)), key=vkey)
    f.parent.mkdir(parents=True, exist_ok=True)
    f.write_text(json.dumps(vs), encoding="utf-8")
    return vs


def dependency_tree(name: str, version: str, eco: str = "npm", offline: bool = False) -> list[dict] | None:
    """Resolved dependency tree of one published package version (deps.dev): [{name, version, relation}]."""
    system = {"npm": "npm", "PyPI": "pypi", "Maven": "maven"}.get(eco)
    if not system:
        return None
    f = CACHE / "depsdev" / (re.sub(r"[^A-Za-z0-9_.-]", "_", f"{eco}_{name}_{version}") + ".json")
    if f.exists():
        data = json.loads(f.read_text(encoding="utf-8"))
    elif offline:
        return None
    else:
        url = (f"https://api.deps.dev/v3/systems/{system}/packages/{urllib.parse.quote(name, safe='')}"
               f"/versions/{urllib.parse.quote(version, safe='')}:dependencies")
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=20) as r:
                data = json.loads(r.read())
        except Exception:
            return None
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(json.dumps(data), encoding="utf-8")
    return [{"name": n["versionKey"]["name"], "version": n["versionKey"]["version"], "relation": n.get("relation")}
            for n in data.get("nodes", []) if n.get("relation") != "SELF"]


def known_vulns(pkgs: list[tuple[str, str]], eco: str, offline: bool = False) -> dict[str, list[str]]:
    """OSV ids per 'name@version' for a list of packages (batched, cached)."""
    idx_f = CACHE / "osv_index.json"
    index = json.loads(idx_f.read_text()) if idx_f.exists() else {}
    out, todo = {}, []
    for n, v in pkgs:
        cid = f"{eco}:{n}@{v}"
        if cid in index:
            if index[cid]:
                out[f"{n}@{v}"] = index[cid]
        else:
            todo.append((n, v))
    if todo and not offline:
        try:
            res = osv_http("https://api.osv.dev/v1/querybatch",
                           {"queries": [{"package": {"name": n, "ecosystem": eco}, "version": v} for n, v in todo]}, 60)
            for (n, v), r in zip(todo, res.get("results", [])):
                ids = [x["id"] for x in r.get("vulns", [])]
                index[f"{eco}:{n}@{v}"] = ids
                if ids:
                    out[f"{n}@{v}"] = ids
            idx_f.parent.mkdir(parents=True, exist_ok=True)
            idx_f.write_text(json.dumps(index))
        except Exception:
            pass
    return out


class Facts:
    """Read-only fact store for one scanned repository."""

    def __init__(self, doc: dict, offline: bool = False, intel: dict | None = None):
        self.doc, self.offline = doc, offline
        self.repo = Path(doc["repository"]["path"])
        self.findings = {f["id"]: f for f in doc["findings"]}
        self.intel = intel or {"kev": set(), "epss": {}}
        self._idx = None

    # --- repository facts -------------------------------------------------------------
    def code_usage(self, package: str, eco: str = "npm") -> dict:
        from ..analyze.reachability import Index
        if self._idx is None:
            self._idx = Index(self.repo)
        hits = self._idx.uses(package, eco)
        return {"package": package, "imports": [f"{a}:{b}" for a, b in hits[:10]], "count": len(hits)}

    def file_lines(self, file: str, line: int | None = None, context: int = 3) -> dict:
        p = (self.repo / file).resolve()
        if self.repo.resolve() not in p.parents or not p.is_file():
            return {"error": "file not in repository"}
        lines = p.read_text(encoding="utf-8", errors="replace").splitlines()
        if line:
            lo, hi = max(1, int(line) - context), min(len(lines), int(line) + context)
        else:
            lo, hi = 1, min(len(lines), 40)
        return {"file": file, "lines": {i: lines[i - 1][:200] for i in range(lo, hi + 1)}}

    def file_line_exists(self, ref: str) -> bool:
        m = re.match(r"^(.*?):(\d+)$", ref.strip())
        if not m:
            return (self.repo / ref).is_file()
        p = self.repo / m.group(1)
        return p.is_file() and int(m.group(2)) <= len(p.read_text(encoding="utf-8", errors="replace").splitlines())

    # --- public data facts ------------------------------------------------------------
    def advisory(self, vuln_id: str) -> dict:
        f = OSV_CACHE / f"{vuln_id}.json"
        if not f.exists():
            return {"error": f"advisory {vuln_id} not available"}
        v = json.loads(f.read_text(encoding="utf-8"))
        ranges = [{"package": a.get("package", {}).get("name"), "events": r.get("events")}
                  for a in v.get("affected", []) for r in a.get("ranges", []) if r.get("type") != "GIT"]
        return {"id": v["id"], "aliases": v.get("aliases"), "summary": v.get("summary"),
                "details": (v.get("details") or "")[:900], "ranges": ranges[:6]}

    def registry_info(self, package: str, version: str, eco: str = "npm") -> dict:
        if eco != "npm":
            return {"note": f"registry metadata available for npm only ({eco})"}
        m = registry_get(f"https://registry.npmjs.org/{urllib.parse.quote(package, safe='@')}/{version}",
                         f"npm_{package}_{version}", self.offline)
        if not m:
            return {"error": "not found in registry"}
        return {"name": m.get("name"), "version": m.get("version"), "repository": m.get("repository"),
                "maintainers": [x.get("name") for x in m.get("maintainers", []) if isinstance(x, dict)],
                "publisher": (m.get("_npmUser") or {}).get("name"), "deprecated": m.get("deprecated"),
                "install_scripts": {k: v for k, v in (m.get("scripts") or {}).items() if k in ("preinstall", "install", "postinstall")},
                "dependencies": list((m.get("dependencies") or {}).keys())[:20]}

    def downloads(self, names: list[str]) -> dict:
        return _downloads([n for n in names if n][:20], self.offline)

    def versions(self, package: str, eco: str = "npm") -> list[str] | None:
        return published_versions(package, eco, self.offline)

    def tree(self, package: str, version: str, eco: str = "npm") -> list[dict] | None:
        return dependency_tree(package, version, eco, self.offline)

    def tree_vulns(self, package: str, version: str, eco: str = "npm") -> dict | None:
        """Known vulnerabilities inside a candidate version's own dependency tree (and the package itself)."""
        t = self.tree(package, version, eco)
        if t is None:
            return None
        pkgs = [(package, version)] + [(n["name"], n["version"]) for n in t]
        return known_vulns(pkgs, eco, self.offline)

    def safe_upgrade(self, package: str, need: str, eco: str = "npm", current: str = "") -> dict:
        """Smallest-impact version >= need whose own dependency tree has no known vulnerability.
        Tries the latest release of the fixed version's major line first, then each later major."""
        vs = self.versions(package, eco) or []
        ok = [v for v in vs if not need or vkey(v) >= vkey(need)]
        if not ok:
            return {"error": "no published version at or above the fixed version"}
        by_major: dict[int, str] = {}
        for v in ok:
            by_major[vkey(v)[0]] = v                       # keeps the latest of each major
        tried = []
        for major in sorted(by_major):
            cand = by_major[major]
            tv = self.tree_vulns(package, cand, eco)
            tried.append({"version": cand, "tree_vulnerabilities": None if tv is None else sorted(tv)})
            if tv is not None and not tv:
                return {"version": cand, "clean_tree": True, "tried": tried}
        first = by_major[min(by_major)]
        return {"version": first, "clean_tree": False, "tried": tried,
                "note": "no candidate with a fully clean dependency tree; smallest-impact version chosen"}

    def exploit_intel(self, cves: list[str]) -> dict:
        return {c: {"epss": self.intel["epss"].get(c), "in_cisa_kev": c in self.intel["kev"]} for c in cves}

    def baseline_changes(self, component_id: str) -> dict:
        ch = self.doc.get("changes") or {}
        hits = [x for k in ("tampered", "added", "changed") for x in ch.get(k, []) if x.get("id") == component_id]
        return {"baseline": ch.get("baseline"), "changes": hits} if ch else {"note": "no baseline comparison in this scan"}
